export const CUSTOM_98_SIMULATIONS_MAP: Record<string, Custom98SimSpec> =
  Object.fromEntries(RAW_98_SPECS.map((spec) => [spec.moduleId, spec]));

export function getCustom98SimulationByModuleId(
  moduleId: string
): Custom98SimSpec | undefined {
  return CUSTOM_98_SIMULATIONS_MAP[moduleId];
}

export function isCustom98SimulationModule(moduleId: string): boolean {
  return Boolean(CUSTOM_98_SIMULATIONS_MAP[moduleId]);
}

/**
 * Replaces simulation metadata on any of the first 7 modules (M1–M7) of a chapter
 * while preserving Module 8 wrap-ups untouched.
 */
export function applyCustom98SimulationToModule(
  mod: Part1ModuleItem,
  indexInChapter: number
): Part1ModuleItem {
  if (mod.isWrapUpModule || indexInChapter >= 7) {
    return mod;
  }
  const spec = CUSTOM_98_SIMULATIONS_MAP[mod.id];
  if (!spec) {
    return mod;
  }
  return {
    ...mod,
    simulation: {
      title: spec.title,
      description: spec.description,
      interactionType: spec.interactionType,
      defaultControlA: spec.defaultControlA,
      defaultControlB: spec.defaultControlB,
      controlALabel: spec.controlALabel,
      controlAMin: spec.controlAMin,
      controlAMax: spec.controlAMax,
      controlBLabel: spec.controlBLabel,
      controlBMin: spec.controlBMin,
      controlBMax: spec.controlBMax,
      formulaHighlight: spec.formulaHighlight,
    },
  };
}

export function applyCustom98SimulationsToChapter(
  chapter: Part1ChapterCurriculum
): Part1ChapterCurriculum {
  if (!chapter.modules || chapter.modules.length === 0) {
    return chapter;
  }
  return {
    ...chapter,
    modules: chapter.modules.map((mod, idx) =>
      applyCustom98SimulationToModule(mod, idx)
    ),
  };
}
