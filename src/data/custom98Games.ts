export const CUSTOM_98_GAMES_MAP: Record<string, Custom98GameSpec> =
  Object.fromEntries(RAW_98_GAMES.map((spec) => [spec.moduleId, spec]));

export function getCustom98GameByModuleId(
  moduleId: string
): Custom98GameSpec | undefined {
  return CUSTOM_98_GAMES_MAP[moduleId];
}

export function isCustom98GameModule(moduleId: string): boolean {
  return Boolean(CUSTOM_98_GAMES_MAP[moduleId]);
}

export function applyCustom98GamesToModule(
  mod: Part1ModuleItem,
  indexInChapter: number
): Part1ModuleItem {
  if (mod.isWrapUpModule || indexInChapter >= 7) {
    return mod;
  }
  const spec = CUSTOM_98_GAMES_MAP[mod.id];
  if (!spec) {
    return mod;
  }
  return {
    ...mod,
    game: {
      ...mod.game,
      title: spec.title,
      subtitle: spec.subtitle,
      rules: spec.rules,
    },
  };
}

export function applyCustom98GamesToChapter(
  chapter: Part1ChapterCurriculum
): Part1ChapterCurriculum {
  if (!chapter.modules || chapter.modules.length === 0) {
    return chapter;
  }
  return {
    ...chapter,
    modules: chapter.modules.map((mod, idx) =>
      applyCustom98GamesToModule(mod, idx)
    ),
  };
}
